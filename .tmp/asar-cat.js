const fs = require("node:fs");
const path = require("node:path");
const base = "C:\\Users\\HaoNaN\\AppData\\Local\\Programs\\DeepSeek Harness\\resources\\app.asar\\dsh\\node_modules\\@deepseek-ai";
const [rel, startArg, endArg] = process.argv.slice(2);
const full = path.join(base, rel);
const lines = fs.readFileSync(full, "utf8").split(/\r?\n/);
const start = Math.max(1, Number(startArg || 1));
const end = Math.min(lines.length, Number(endArg || 200));
const out = [];
for (let i = start; i <= end; i += 1) out.push(i + ": " + lines[i - 1]);
fs.writeFileSync("D:\\workspace\\HNFlow\\.tmp\\cat-out.txt", out.join("\n"));
console.log("lines", lines.length, "printed", start + "-" + end);
